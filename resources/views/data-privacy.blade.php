  <p>
    The <strong>Local Government Unit of Mabinay (Municipality of Mabinay)</strong>, as the Personal Information Controller (PIC), together with <strong>EAJ Web Development Services</strong> as the System Developer and Technical Service Provider, are committed to protecting and respecting your personal data privacy in full compliance with <strong><a href="https://privacy.gov.ph/data-privacy-act/" target="_blank" style="color: #00695c; text-decoration: underline;">Republic Act No. 10173</a> (Data Privacy Act of 2012)</strong>, its Implementing Rules and Regulations (IRR), and guidelines issued by the National Privacy Commission (NPC).
  </p>

  <h4 style="color: #00695c; font-size: 16px; font-weight: 700; margin-top: 24px; margin-bottom: 10px; border-left: 4px solid #00695c; padding-left: 10px;">
    1. Scope &amp; Categories of Data Collected
  </h4>
  <p>To provide an integrated Human Resource Information System (HRIS), daily timekeeping, and strategic performance evaluation, the system collects and processes the following information:</p>
  <ul style="margin-left: 20px; margin-top: 8px; margin-bottom: 16px;">
    <li><strong>Personal Identifiers:</strong> Full name, employee ID number, birth date, gender, civil status, contact information, residential address, and department assignment.</li>
    <li><strong>Employment &amp; Career Records:</strong> Personal Data Sheet (PDS / CS Form 212), position title, employment status (Regular, Permanent, Casual, JO, COS), appointment details, and service history.</li>
    <li><strong>Time &amp; Attendance Logs:</strong> Biometric facial recognition data, digital time logs, Daily Time Records (DTR), leave applications, travel orders, and pass slips.</li>
    <li><strong>Strategic Performance Records (SPMS):</strong> Office Performance Commitment &amp; Review (OPCR), Individual Performance Commitment &amp; Review (IPCR), target metrics, actual accomplishments, and evaluation ratings.</li>
  </ul>

  <h4 style="color: #00695c; font-size: 16px; font-weight: 700; margin-top: 24px; margin-bottom: 10px; border-left: 4px solid #00695c; padding-left: 10px;">
    2. Purpose of Collection &amp; Processing
  </h4>
  <p>All personal data collected through the system is processed strictly for legitimate municipal government operations and administration, including:</p>
  <ul style="margin-left: 20px; margin-top: 8px; margin-bottom: 16px;">
    <li>Maintaining accurate digital personnel profiles and Personal Data Sheets (PDS) in the HRIS portal.</li>
    <li>Tracking daily attendance, processing official leave requests, and generating DTR logs for payroll.</li>
    <li>Evaluating staff performance under the Civil Service Commission (CSC) Strategic Performance Management System (SPMS).</li>
    <li>Complying with statutory reporting requirements enforced by the Civil Service Commission (CSC), Commission on Audit (COA), GSIS, and Pag-IBIG.</li>
  </ul>

  <h4 style="color: #00695c; font-size: 16px; font-weight: 700; margin-top: 24px; margin-bottom: 10px; border-left: 4px solid #00695c; padding-left: 10px;">
    3. System Developer &amp; Technical Security Controls
  </h4>
  <p>
    The software architecture, database design, and technical maintenance of the LGU Mabinay HRIS system are engineered and managed by <strong>EAJ Web Development Services</strong>. Technical security measures enforced include:
  </p>
  <ul style="margin-left: 20px; margin-top: 8px; margin-bottom: 16px;">
    <li><strong>Role-Based Access Control:</strong> Strict permissions limiting access to authorized personnel, office heads, and HR administrators.</li>
    <li><strong>Data Security &amp; Encryption:</strong> Encrypted password storage, HTTPS encrypted data transmission, and protected database backups.</li>
    <li><strong>System Integrity:</strong> Continuous maintenance, software optimization, and privacy-by-design standards implemented by <strong>EAJ Web Development Services</strong>.</li>
  </ul>

  <h4 style="color: #00695c; font-size: 16px; font-weight: 700; margin-top: 24px; margin-bottom: 10px; border-left: 4px solid #00695c; padding-left: 10px;">
    4. Data Retention &amp; Custody
  </h4>
  <p>
    All physical and electronic records are held under the primary custody of the <strong>Human Resource Management Office (HRMO)</strong> of the Municipality of Mabinay. Data is retained only for as long as necessary to fulfill statutory duties and government audit requirements.
  </p>

  <h4 style="color: #00695c; font-size: 16px; font-weight: 700; margin-top: 24px; margin-bottom: 10px; border-left: 4px solid #00695c; padding-left: 10px;">
    5. Rights of Data Subjects
  </h4>
  <p>Under Republic Act No. 10173, employees and data subjects have the right to be informed, to access their personal records, to request correction of inaccuracies, and to lodge inquiries regarding their data processing with the HRMO.</p>

  <h4 style="color: #00695c; font-size: 16px; font-weight: 700; margin-top: 24px; margin-bottom: 10px; border-left: 4px solid #00695c; padding-left: 10px;">
    6. Consent &amp; Acknowledgment
  </h4>
  <p>
    By accessing or submitting information through the LGU Mabinay HRIS Portal, you acknowledge that you have read this notice and voluntarily consent to the collection, processing, and storage of your personal data by the Municipality of Mabinay HRMO and technical management by <strong>EAJ Web Development Services</strong>.
  </p>

